    private void btnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeleccionarActionPerformed
        // TODO add your handling code here:
        int fila = TablaProductos.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto");
            return;
        }

        if (TablaProductos.getValueAt(fila, 0) == null) {
            JOptionPane.showMessageDialog(this, "No hay datos en la fila seleccionada");
            return;
        }

        try {
            // Obtener precio del producto
            double precio = Double.parseDouble(TablaProductos.getValueAt(fila, 4).toString());

            // Validar que txtCantidad no esté vacío
            String cantidadTexto = txtCantidad.getText().trim();
            if (cantidadTexto.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ingrese una cantidad");
                txtCantidad.requestFocus();
                return;
            }

            int cantidad = Integer.parseInt(cantidadTexto);

            if (cantidad <= 0) {
                JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a 0");
                txtCantidad.requestFocus();
                return;
            }

            // Calcular subtotal del producto
            double totalProducto = precio * cantidad;

            // Actualizar el total en la ventana principal
            if (ventanaPrincipal != null) {
                System.out.println("Actualizando total con: $" + String.format("%.2f", totalProducto)); 

                ventanaPrincipal.actualizarTotal(totalProducto);

                JOptionPane.showMessageDialog(this,
                        "Producto agregado exitosamente\n\n"
                        + "Producto: " + TablaProductos.getValueAt(fila, 1) + "\n"
                        + "Precio unitario: $" + String.format("%.2f", precio) + "\n"
                        + "Cantidad: " + cantidad + "\n"
                        + "Subtotal: $" + String.format("%.2f", totalProducto),
                        "Producto Agregado",
                        JOptionPane.INFORMATION_MESSAGE);

                // Limpiar el campo de cantidad después de agregar
                txtCantidad.setText("");
                txtCantidad.requestFocus();

            } else {
                System.out.println("ERROR: ventanaPrincipal es NULL"); 
                JOptionPane.showMessageDialog(this,
                        "Error: No se puede actualizar el total.\nLa conexión con la ventana principal falló.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese una cantidad válida (solo números enteros)",
                    "Error de validación",
                    JOptionPane.WARNING_MESSAGE);
            txtCantidad.requestFocus();
            txtCantidad.selectAll();
        }
    }//GEN-LAST:event_btnSeleccionarActionPerformed

