    public void mostrarProducto(int opcionBuscar, String valor) {
        DefaultTableModel tProducto = new DefaultTableModel();
        tProducto.addColumn("ID");
        tProducto.addColumn("Nombre");
        tProducto.addColumn("Descripción");
        tProducto.addColumn("Categoría");
        tProducto.addColumn("Precio");

        String baseSelect = "SELECT p.producto_id, p.nombre, p.descripcion, "
                + "COALESCE(c.nombre_categoria, '') AS categoria, p.precio "
                + "FROM producto p LEFT JOIN categoria c ON p.categoria_id = c.categoria_id";

        String sql;
        if (opcionBuscar == 0 && valor == null) {
            sql = baseSelect;
        } else if (opcionBuscar == 1 && valor != null) {
            sql = baseSelect + " WHERE p.nombre LIKE ?";
        } else if (opcionBuscar == 2 && valor != null) {
            sql = baseSelect + " WHERE c.nombre_categoria = ?";
        } else {
            sql = baseSelect;
        }

        String[] datos = new String[5];
        try {
            PreparedStatement ps = cn.prepareStatement(sql);

            if (opcionBuscar == 1 && valor != null) {
                ps.setString(1, "%" + valor + "%");
            } else if (opcionBuscar == 2 && valor != null) {
                ps.setString(1, valor);
            }

            ResultSet rs = ps.executeQuery();

            // Limpiar la tabla antes de agregar nuevos datos
            tProducto.setRowCount(0);

            while (rs.next()) {
                datos[0] = rs.getString("producto_id");
                datos[1] = rs.getString("nombre");
                datos[2] = rs.getString("descripcion");
                datos[3] = rs.getString("categoria");  // alias from JOIN
                datos[4] = rs.getString("precio");
                tProducto.addRow(datos.clone());
            }

            rs.close();
            ps.close();

            // Actualizar el modelo de la tabla
            TablaProductos.setModel(tProducto);

            // DEBUG: Mostrar cuántas filas se cargaron
            System.out.println("Filas cargadas: " + tProducto.getRowCount());

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null,
                    "Error al cargar productos: " + e.getMessage(),
                    "Error de Base de Datos", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

